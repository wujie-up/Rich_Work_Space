import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Workspace } from '../src/main/common/workspace.js';
import { springApps, SpringRunner } from '../src/main/common/spring.js';

test('discovers module main classes, ignores comments/tests, starts and cleans process group', async t => {
  const root = await mkdtemp(join(tmpdir(), 'coding-spring-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, 'module/src/main/java/demo'), { recursive: true });
  await mkdir(join(root, 'module/src/test/java'), { recursive: true });
  await writeFile(join(root, 'module/pom.xml'), '<project/>');
  const source = 'package demo; @SpringBootApplication public class App { public static void main(String[] args) {} }';
  await writeFile(join(root, 'module/src/main/java/demo/App.java'), source);
  await writeFile(join(root, 'module/src/main/java/demo/Comment.java'), `/* ${source} */`);
  await writeFile(join(root, 'module/src/test/java/Test.java'), source);
  await writeFile(join(root, 'mvnw'), '#!/bin/sh\nprintf "%s\\n" "$@"\nsleep 60\n');
  const workspace = await Workspace.open(root);
  const result = await springApps(workspace);
  assert.equal(result.apps.length, 1);
  assert.equal(result.apps[0].module, 'module');
  assert.equal(result.apps[0].mainClass, 'demo.App');
  let owned = [];
  const runner = new SpringRunner(pids => { owned = pids; });
  t.after(() => runner.stop());
  const task = await runner.start(workspace, result.apps[0]);
  assert.equal(task.state, 'running');
  assert.equal(owned.length, 1);
  const pid = owned[0];
  await assert.rejects(runner.start(workspace, result.apps[0]), /已经在运行/);
  assert.match(task.command, /spring-boot:run.*demo.App/);
  assert.equal((await runner.cancel(task.id)).state, 'stopped');
  assert.deepEqual(owned, []);
  assert.throws(() => process.kill(pid, 0), { code: 'ESRCH' });
  await runner.start(workspace, result.apps[0]);
  const restartedPid = owned[0];
  await runner.stop();
  assert.deepEqual(owned, []);
  assert.throws(() => process.kill(restartedPid, 0), { code: 'ESRCH' });
});
