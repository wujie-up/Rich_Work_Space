import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { launch, openConfiguration } from '../../../../desk/test/electron/helpers.js';

test('工作流分组完整生命周期：空组、改名、移动、删除、草稿保护及折叠持久化；明暗主题和窄窗口', { timeout: 120000 }, async t => {
  const { app, page } = await launch(t, { openPlugin: false, prepareData: data => writeFile(resolve(data, 'plugins.json'), '[]') });
  page.setDefaultTimeout(7000);
  const { version } = JSON.parse(await readFile('plugin-dev/work-flow/plugin.json', 'utf8'));
  await app.evaluate(({ dialog }, path) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] });
  }, resolve(`plugin-dev/dist/work-flow-${version}.plg`));
  await page.evaluate(() => workDesk.plugins.install());
  await page.evaluate(() => workDesk.plugins.enable('work-flow'));
  const invoke = (method, ...args) => page.evaluate(({ method, args }) => workDesk.plugins.invoke('work-flow', method, args), { method, args });
  const stages = [];
  for (let index = 1; index <= 7; index++) {
    stages.push(await invoke('workflows.save', { name: `研发阶段 ${index}`, nodes: [{ id: 'input', type: 'text.input' }], edges: [] }));
  }
  const old = await invoke('workflows.save', { name: '旧流程', nodes: [{ id: 'input', type: 'text.input' }], edges: [] });
  await page.locator('.shelf-app[data-plugin="work-flow"]').click();
  const frame = page.frameLocator('iframe.plugin-view:visible[src^="desk-plugin://work-flow/"]');
  await frame.getByRole('button', { name: '新建分组', exact: true }).waitFor({ timeout: 5000 });
  const ungrouped = frame.locator('.workflow-ungrouped');
  assert.equal(await ungrouped.locator('summary span').textContent(), '未分组', '没有自定义分组时也显示默认分组');
  assert.equal(await ungrouped.locator('summary small').textContent(), String((await invoke('workflows.list')).length));
  await ungrouped.locator('summary').click();
  assert.equal(await ungrouped.locator('[data-workflow]').first().isVisible(), false);
  await frame.locator('#workflow-name').fill('未保存编辑');
  assert.equal(await ungrouped.getAttribute('open'), null, '刷新列表保留默认分组折叠状态');
  await ungrouped.locator('summary').focus();
  await page.keyboard.press('Enter');
  await ungrouped.locator(`[data-workflow-row="${stages[6].id}"]`).dragTo(
    ungrouped.locator(`[data-workflow-row="${old.id}"]`), { targetPosition: { x: 20, y: 2 } });
  await page.waitForTimeout(200);
  assert.equal((await invoke('workflows.list'))[0].id, stages[6].id, '默认分组支持拖动排序');
  await ungrouped.locator(`[data-workflow-row="${old.id}"]`).dragTo(
    ungrouped.locator(`[data-workflow-row="${stages[6].id}"]`), { targetPosition: { x: 20, y: 2 } });
  await page.waitForTimeout(200);
  await ungrouped.locator('summary').click({ button: 'right', position: { x: 45, y: 12 } });
  const defaultMenu = frame.getByRole('menu', { name: '工作流分组操作', exact: true });
  assert.deepEqual(await defaultMenu.getByRole('menuitem').allTextContents(), ['新建工作流']);
  const headingBox = await ungrouped.locator('summary').boundingBox();
  const defaultMenuBox = await defaultMenu.boundingBox();
  assert.ok(Math.abs(defaultMenuBox.x - (headingBox.x + 45 + 8)) < 2, '菜单紧邻右键位置，而非整行右边缘');
  assert.ok(Math.abs(defaultMenuBox.y - (headingBox.y + 12)) < 2, '菜单与点击位置纵向对齐');
  await page.keyboard.press('Escape');
  const dialog = frame.getByRole('dialog', { name: '工作流分组', exact: true });
  const create = frame.getByRole('dialog', { name: '新建分组', exact: true });
  const makeGroup = async name => {
    await frame.getByRole('button', { name: '新建分组', exact: true }).click();
    await create.getByLabel('分组名称', { exact: true }).fill(name);
    await create.getByRole('button', { name: '创建分组', exact: true }).click();
    await create.waitFor({ state: 'detached' });
  };
  await frame.getByRole('button', { name: '新建分组', exact: true }).click();
  await create.getByRole('button', { name: '创建分组', exact: true }).click();
  await create.getByRole('alert').filter({ hasText: '请输入分组名称' }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal((await invoke('workflows.groups')).length, 0);
  await makeGroup('  软件研发七阶段  ');
  const groupId = (await invoke('workflows.groups'))[0].id;
  const group = frame.locator(`.workflow-group[data-group-id="${groupId}"]`);
  assert.equal(await group.locator('[data-workflow]').count(), 0, '空组独立存在');
  const groupOrder = () => frame.locator('.workflow-group').evaluateAll(items => items.map(item => item.dataset.groupId));
  await ungrouped.locator('summary').dragTo(group.locator('summary'), { targetPosition: { x: 20, y: 2 } });
  await page.waitForTimeout(200);
  assert.deepEqual(await groupOrder(), ['', groupId], '拖动默认分组到自定义分组前');
  assert.deepEqual((await invoke('workflows.groups', { includeUngrouped: true })).map(item => item.id), ['', groupId]);
  await group.locator('summary').focus();
  await page.keyboard.press('Alt+ArrowUp');
  await page.waitForTimeout(200);
  assert.deepEqual(await groupOrder(), [groupId, ''], '键盘也可以调整顺序');
  const menu = frame.getByRole('menu', { name: '工作流分组操作', exact: true });
  const groupAction = async (target, name) => {
    await target.locator('summary').click({ button: 'right' });
    await menu.getByRole('menuitem', { name, exact: true }).click();
  };
  await group.locator('summary').click({ button: 'right' });
  await menu.waitFor();
  assert.deepEqual(await menu.getByRole('menuitem').allTextContents(), ['重命名分组', '新建工作流', '删除分组']);
  await page.keyboard.press('End');
  assert.equal(await menu.getByRole('menuitem', { name: '删除分组', exact: true }).evaluate(item => item === document.activeElement), true);
  await page.keyboard.press('Escape');
  await menu.waitFor({ state: 'detached' });
  const restoredFocus = await group.locator('summary').evaluate(async item => {
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    return { restored: item === document.activeElement, active: document.activeElement?.outerHTML.slice(0, 300) };
  });
  assert.equal(restoredFocus.restored, true, JSON.stringify(restoredFocus));
  await page.keyboard.press('Shift+F10');
  await menu.waitFor();
  await frame.locator('#workflow-name').click();
  await menu.waitFor({ state: 'detached' });
  assert.equal((await invoke('workflows.groups')).length, 1, '取消菜单不删除分组');
  assert.equal(await group.locator('summary button, [data-add]').count(), 0, '操作仅在右键菜单显示');
  await frame.getByRole('button', { name: '新建分组', exact: true }).click();
  await create.getByLabel('分组名称', { exact: true }).fill('软件研发七阶段');
  await create.getByRole('button', { name: '创建分组', exact: true }).click();
  await create.getByRole('alert').filter({ hasText: '已存在' }).waitFor();
  await frame.locator('#workflow-name').click();
  await create.waitFor({ state: 'detached' });
  assert.equal((await invoke('workflows.groups')).length, 1, '外部点击取消不创建分组');
  const move = async (workflow, name) => {
    await frame.locator(`[data-workflow="${workflow.id}"]`).click();
    await frame.getByRole('button', { name: '设置工作流分组', exact: true }).click();
    await dialog.getByRole('combobox', { name: '所属分组', exact: true }).selectOption({ label: name || '未分组' });
    await dialog.getByRole('button', { name: '确认分组', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    assert.equal((await invoke('workflows.list')).find(item => item.id === workflow.id).group, name || undefined,
      '移动确认即保存，无需保存整个流程');
  };
  for (const stage of stages) { await move(stage, '软件研发七阶段'); }
  assert.equal(await group.locator('[data-workflow]').count(), 7);
  assert.equal(await group.locator('summary').getAttribute('title'), '软件研发七阶段');
  assert.equal((await invoke('workflows.list')).filter(item => item.group === '软件研发七阶段').length, 7);
  const order = async () => group.locator('[data-workflow]').evaluateAll(items => items.map(item => item.dataset.workflow));
  assert.equal(await group.getByRole('button', { name: /[上下]移工作流/ }).count(), 0, '不显示点击排序按钮');
  const expectedOrder = (await order()).filter(id => id !== stages[6].id);
  expectedOrder.splice(expectedOrder.indexOf(stages[4].id), 0, stages[6].id);
  await group.locator(`[data-workflow-row="${stages[6].id}"]`).dragTo(
    group.locator(`[data-workflow-row="${stages[4].id}"]`), { targetPosition: { x: 20, y: 2 } });
  await page.waitForTimeout(200);
  assert.deepEqual(await order(), expectedOrder, 'drag reorders only group members');
  const reordered = await order();
  await group.locator(`[data-workflow-row="${stages[6].id}"]`).dragTo(frame.locator(`[data-workflow="${old.id}"]`));
  assert.deepEqual(await order(), reordered, 'cross-group drop cannot move or reorder');
  await frame.locator(`[data-workflow="${stages[6].id}"]`).click();
  const rename = frame.getByRole('dialog', { name: '重命名分组', exact: true });
  await frame.locator('#workflow-name').fill('尚未保存的流程名称');
  await groupAction(group, '重命名分组');
  assert.equal(await group.getAttribute('open'), '', '右键菜单不折叠分组');
  await rename.getByLabel('分组名称', { exact: true }).fill('');
  await rename.getByRole('button', { name: '保存分组名称', exact: true }).click();
  await rename.getByRole('alert').filter({ hasText: '请输入分组名称' }).waitFor();
  await rename.getByLabel('分组名称', { exact: true }).fill('取消的名称');
  await page.keyboard.press('Escape');
  assert.equal((await invoke('workflows.list')).filter(item => item.group === '软件研发七阶段').length, 7);
  await groupAction(group, '重命名分组');
  await rename.getByLabel('分组名称', { exact: true }).fill('软件研发 <七阶段>');
  await page.keyboard.press('Enter');
  await rename.waitFor({ state: 'detached' });
  assert.equal(await group.locator('summary').getAttribute('title'), '软件研发 <七阶段>');
  assert.equal(await group.locator('summary').evaluate(button => button === document.activeElement), true);
  assert.equal(await frame.locator('#workflow-name').inputValue(), '尚未保存的流程名称', '重命名保留未保存编辑');
  const stored = await invoke('workflows.list');
  assert.equal(stored.filter(item => item.group === '软件研发 <七阶段>').length, 7);
  assert.equal(stored.find(item => item.id === stages[6].id).name, '研发阶段 7', '分组改名不保存其他草稿字段');
  await groupAction(group, '重命名分组');
  await rename.getByLabel('分组名称', { exact: true }).fill('软件研发七阶段');
  await rename.getByRole('button', { name: '保存分组名称', exact: true }).click();
  await rename.waitFor({ state: 'detached' });
  await group.locator('summary').click();
  assert.equal(await group.locator('[data-workflow]').first().isVisible(), false);
  await frame.locator(`[data-workflow="${old.id}"]`).click();
  assert.equal(await group.getAttribute('open'), null, '切换或刷新界面保留当前收起状态');
  await group.locator('summary').focus();
  await page.keyboard.press('Enter');
  assert.equal(await group.locator('[data-workflow]').first().isVisible(), true);
  await move(stages[6], '');
  assert.equal(await group.locator('[data-workflow]').count(), 6);
  await frame.getByRole('button', { name: '设置工作流分组', exact: true }).click();
  await dialog.getByRole('combobox', { name: '所属分组', exact: true }).selectOption({ label: '软件研发七阶段' });
  await page.keyboard.press('Escape');
  assert.equal((await invoke('workflows.list')).find(item => item.id === stages[6].id).group, undefined);
  await move(stages[6], '软件研发七阶段');
  await group.locator('summary').click();
  await groupAction(group, '重命名分组');
  await rename.getByLabel('分组名称', { exact: true }).fill('已保存的研发分组');
  await rename.getByRole('button', { name: '保存分组名称', exact: true }).click();
  await rename.waitFor({ state: 'detached' });
  assert.equal(await group.getAttribute('open'), null, '整组改名保留收起状态');
  await page.reload();
  await page.locator('.shelf-app[data-plugin="work-flow"]').click();
  await group.locator('summary').waitFor();
  assert.deepEqual(await groupOrder(), [groupId, ''], '重开后保留分组顺序');
  assert.equal(await group.getAttribute('open'), null, '重载后保留收起状态');
  await group.locator('summary').click();
  await group.locator('[data-workflow]').first().waitFor();
  assert.equal(await group.locator('[data-workflow]').count(), 7);
  assert.equal(await group.locator('summary').getAttribute('title'), '已保存的研发分组', '重新加载后保留新组名');
  assert.equal((await invoke('workflows.list')).find(item => item.id === old.id).group, undefined);
  assert.deepEqual(await order(), reordered, 'reload preserves within-group order');
  await mkdir('.test-results/work-flow', { recursive: true });
  const theme = async mode => {
    await page.locator('#desktop').click();
    await openConfiguration(page);
    await page.locator('#theme-settings').click();
    await page.locator('#theme-mode').selectOption(mode);
    await page.getByRole('button', { name: '关闭配置', exact: true }).click();
    await page.reload();
    await page.locator('.shelf-app[data-plugin="work-flow"]').click();
    await frame.locator(`html[data-theme="${mode}"]`).waitFor();
  };
  await theme('dark');
  await group.locator('summary').click({ button: 'right' });
  await page.screenshot({ path: '.test-results/work-flow/groups-dark.png' });
  await page.keyboard.press('Escape');
  await theme('light');
  await group.locator('summary').click({ button: 'right' });
  await page.screenshot({ path: '.test-results/work-flow/groups-light.png' });
  await page.keyboard.press('Escape');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 700));
  await page.waitForFunction(() => window.innerWidth <= 900);
  await group.locator('summary').click({ button: 'right' });
  const menuBox = await menu.boundingBox();
  assert.ok(menuBox.x >= 0 && menuBox.x + menuBox.width <= 900);
  await menu.getByRole('menuitem', { name: '重命名分组', exact: true }).click();
  const box = await rename.boundingBox();
  assert.ok(box.width < 900 && box.x >= 0 && box.x + box.width <= 900);
  await page.screenshot({ path: '.test-results/work-flow/groups-narrow.png' });
  await page.keyboard.press('Escape');
  await makeGroup('空分组');
  await page.reload();
  await page.locator('.shelf-app[data-plugin="work-flow"]').click();
  const empty = frame.locator('.workflow-group').filter({ has: frame.locator('summary[title="空分组"]') });
  await empty.locator('summary').waitFor();
  assert.equal(await empty.locator('[data-workflow]').count(), 0, '重载保留空组');
  await groupAction(empty, '新建工作流');
  await empty.locator('[data-workflow]').waitFor();
  assert.equal(await empty.locator('[data-workflow]').count(), 1, '可以在空组内新建草稿');
  const localDraftId = await empty.locator('[data-workflow]').getAttribute('data-workflow');
  assert.equal((await invoke('workflows.list')).some(item => item.id === localDraftId), false, '空草稿不写入流程定义');
  await frame.locator(`[data-workflow="${stages[0].id}"]`).click();
  await frame.locator('#workflow-name').fill('删除分组时保留的草稿');
  const before = await invoke('workflows.list');
  const history = await invoke('runs.list', stages[0].id);
  const remove = frame.getByRole('dialog', { name: '删除分组', exact: true });
  await groupAction(group, '删除分组');
  assert.match(await remove.textContent(), /7 个工作流/);
  assert.equal(await remove.getByRole('button', { name: '取消', exact: true }).evaluate(button => button === document.activeElement), true);
  await page.keyboard.press('Escape');
  assert.equal((await invoke('workflows.groups')).length, 2);
  await groupAction(group, '删除分组');
  await remove.getByRole('button', { name: '确认删除分组', exact: true }).click();
  await remove.waitFor({ state: 'detached' });
  const after = await invoke('workflows.list');
  assert.equal(after.length, before.length, '删除组保留所有流程定义');
  assert.equal(after.filter(item => item.groupId === groupId).length, 0);
  assert.deepEqual(await invoke('runs.list', stages[0].id), history);
  assert.equal(await frame.locator('#workflow-name').inputValue(), '删除分组时保留的草稿');
  assert.equal(after.find(item => item.id === stages[0].id).name, '研发阶段 1', '删除组不保存草稿字段');
  assert.equal(await frame.locator('#new-group').evaluate(button => button === document.activeElement), true);
  await groupAction(empty, '删除分组');
  await remove.getByRole('button', { name: '确认删除分组', exact: true }).click();
  await remove.waitFor({ state: 'detached' });
  assert.equal((await invoke('workflows.groups')).length, 0);
  assert.equal(await frame.locator(`.workflow-ungrouped [data-workflow="${localDraftId}"]`).count(), 1, '未保存草稿同样移到未分组');
  await groupAction(ungrouped, '新建工作流');
  await ungrouped.locator('.selected').filter({ hasText: '新建工作流' }).waitFor();
  assert.equal(await ungrouped.locator('.selected').textContent().then(text => text.trim()), '新建工作流');
  assert.equal((await invoke('workflows.groups')).length, 0, '默认组新建不生成自定义分组');
});
