import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { launch, toggleTheme } from '../../../../desk/test/electron/helpers.js';

test('最新 DeskPG：工作流边缘收起、展开与拖动和键盘调宽', { timeout: 120000 }, async t => {
  const { app, page } = await launch(t, { executablePath: '/Applications/DeskPG.app/Contents/MacOS/DeskPG',
    openPlugin: false, prepareData: data => writeFile(resolve(data, 'plugins.json'), '[]') });
  const manifest = JSON.parse(await readFile('plugin-dev/work-flow/plugin.json', 'utf8'));
  await app.evaluate(({ dialog }, file) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] });
  }, resolve(`plugin-dev/dist/work-flow-${manifest.version}.plg`));
  await page.evaluate(() => workDesk.plugins.install());
  await page.evaluate(() => workDesk.plugins.enable('work-flow'));
  const installed = await page.evaluate(() => workDesk.plugins.list());
  assert.equal(installed.find(plugin => plugin.id === 'work-flow').version, manifest.version);
  await page.locator('.shelf-app[data-plugin="work-flow"]').click();
  const frame = page.frameLocator('iframe.plugin-view:visible[src^="desk-plugin://work-flow/"]');
  const toggle = frame.locator('#toggle-list');
  const sidebar = frame.locator('.workflow-sidebar');
  const canvas = frame.locator('.canvas-area');
  await frame.locator('#list button').first().waitFor();
  const width = (await sidebar.boundingBox()).width;
  const before = await canvas.boundingBox();
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await toggle.getAttribute('aria-label'), '展开工作流列表');
  assert.equal(await frame.locator('#new-workflow').isVisible(), false, '收起时整栏隐藏，不保留新建按钮窄栏');
  assert.ok((await canvas.boundingBox()).width >= before.width + width - 1, '画布获得侧栏全部宽度');
  assert.equal(await toggle.isVisible(), true, '左边缘仍可展开');
  await toggle.focus();
  await page.keyboard.press('Enter');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
  assert.equal((await sidebar.boundingBox()).width, width);
  const divider = await toggle.boundingBox();
  await page.mouse.move(divider.x + divider.width / 2, divider.y + divider.height / 2);
  await page.mouse.down();
  await page.mouse.move(divider.x + divider.width / 2 + 80, divider.y + divider.height / 2, { steps: 8 });
  await page.mouse.up();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true', '拖动结束不触发收起');
  assert.ok((await sidebar.boundingBox()).width >= width + 79);
  const resized = (await sidebar.boundingBox()).width;
  await toggle.focus();
  await page.keyboard.press('ArrowRight');
  assert.equal((await sidebar.boundingBox()).width, resized + 20);
  await page.keyboard.press('ArrowLeft');
  assert.equal((await sidebar.boundingBox()).width, resized);
  await page.keyboard.press('Space');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  await toggle.click();
  assert.equal((await sidebar.boundingBox()).width, resized, '展开恢复调整后的宽度');
  await mkdir('.test-results/work-flow', { recursive: true });
  await toggle.hover();
  await page.screenshot({ path: '.test-results/work-flow/sidebar-expanded.png' });
  await page.locator('#desktop').click();
  await toggleTheme(page);
  await page.locator('.shelf-app[data-plugin="work-flow"]').click();
  await toggle.hover();
  await page.screenshot({ path: '.test-results/work-flow/sidebar-theme.png' });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 720));
  await page.waitForFunction(() => window.innerWidth <= 1000);
  const narrow = await canvas.boundingBox();
  const narrowWidth = (await sidebar.boundingBox()).width;
  await toggle.click();
  const collapsed = await canvas.boundingBox();
  const inspector = await frame.locator('aside.inspector').boundingBox();
  assert.ok(Math.abs(collapsed.x - (narrow.x - narrowWidth)) < 1, '窄窗口收起后画布从左边缘开始');
  assert.ok(Math.abs(collapsed.x + collapsed.width - inspector.x) < 1, '画布占满侧栏与属性面板之间的空间');
  await toggle.hover();
  await page.screenshot({ path: '.test-results/work-flow/sidebar-collapsed-narrow.png' });
  await toggle.click();
  assert.equal(await frame.locator('#new-workflow').isVisible(), true);
});
