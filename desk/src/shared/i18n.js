// Unknown messages remain readable; user and plugin content never enters the catalog implicitly.
export function translate(key, language, parameters = {}) {
  const message = language === 'en' ? english[key] || key : key;
  return message.replace(/\{(\w+)\}/g, (match, name) => parameters[name] ?? match);
}
